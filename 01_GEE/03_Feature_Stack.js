/* ============================================================================
   1. RAW SENTINEL-2 BANDS
   ============================================================================ */

var spectralBands = composite.select([
  'B2',
  'B3',
  'B4',
  'B8',
  'B11',
  'B12'
]);


/* ============================================================================
   2. CREATE FEATURE STACK
   ============================================================================ */

var featureImage = spectralBands
  .addBands(ndvi)
  .addBands(ndwi)
  .addBands(mndwi)
  .addBands(ndbi)
  .addBands(ndmi)
  .addBands(nbr)
  .addBands(greenSwir)
  .addBands(nirSwir);


/* ============================================================================
   3. FEATURE NAME LIST
   ============================================================================ */

var bandNames = [
  'B2',
  'B3',
  'B4',
  'B8',
  'B11',
  'B12',
  'NDVI',
  'NDWI',
  'MNDWI',
  'NDBI',
  'NDMI',
  'NBR',
  'GREEN_SWIR',
  'NIR_SWIR'
];


/* ============================================================================
   4. CHECK FEATURE STACK
   ============================================================================ */

print(
  '============================================================'
);

print(
  'FEATURE STACK'
);

print(
  'Feature bands:',
  bandNames
);

print(
  'Feature image:',
  featureImage
);

print(
  '============================================================'
);